/**
 * Generate the per-theme CSS files used by the gallery.
 *
 * Each file is one @marianmeres/design-tokens bundled theme emitted with the
 * kit's variable prefix ("vui-"): light mode on `:root`, dark mode on
 * `:root.dark`. Because every file targets `:root`, only one may be active at a
 * time — the gallery swaps a single `<link>`'s href to switch themes and toggles
 * the `dark` class on `<html>` for light/dark.
 *
 * Components read `--vui-color-*` and fall back to system colors, so a page
 * without any of these files still renders sensibly.
 *
 * THE REBOOT BRIDGE. We emit through `generateThemedCss` (the `/reboot` entry
 * point), not plain `generateThemeCss`, so each file carries the `--bs-*`
 * variables Bootstrap Reboot's rules read *in addition to* the `--vui-color-*`
 * tokens. The two vocabularies never collide, so this costs a page without
 * Reboot nothing but bytes (plus two `a { color: … }` rules per mode, which
 * theme links whether Reboot is loaded or not) — and it is what makes Reboot
 * follow the theme, including `:root.dark`, instead of painting the page
 * Bootstrap's own white/grey. The gallery's reboot toggle demonstrates exactly
 * that; a host without the bridge gets a themed kit on an unthemed page.
 *
 * Run:  deno task themes:build
 */
import { generateThemedCss } from "@marianmeres/design-tokens/reboot";
import { getBundledTheme } from "@marianmeres/design-tokens/themes";

/** The kit's CSS variable prefix. Components read `--vui-color-*`. */
export const PREFIX = "vui-";

/** A small spread of the bundled themes. The first entry is the gallery default. */
export const THEMES = [
	"zinc",
	"slateTealOcean",
	"indigoAmber",
	"emeraldPink",
	"monokaiGreen",
	"redSky",
];

/** camelCase → kebab-case (matches the package's own css filenames). */
export const toKebab = (s: string): string => s.replace(/([A-Z])/g, "-$1").toLowerCase();

if (import.meta.main) {
	const dir = new URL(".", import.meta.url).pathname;
	for (const name of THEMES) {
		const schema = getBundledTheme(name);
		if (!schema) {
			console.warn(`! unknown theme "${name}" — skipped`);
			continue;
		}
		const header =
			`/*\n * @marianmeres/design-tokens "${name}" theme + Bootstrap Reboot bridge,\n` +
			` * prefix "${PREFIX}". Generated by gallery/themes/_generate.ts — do not\n` +
			` * edit by hand. Light on :root, dark on :root.dark.\n */\n`;
		const css = generateThemedCss(schema, PREFIX, { prettierIgnore: true });
		await Deno.writeTextFile(`${dir}${toKebab(name)}.css`, header + css);
	}
	console.log(
		`Generated ${THEMES.length} theme files in gallery/themes/ (prefix "${PREFIX}").`,
	);
}
